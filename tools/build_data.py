#!/usr/bin/env python3
"""Generate app/js/data.js from content/vocab.tsv and content/ui.tsv."""
import json, re, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent

def rows(path):
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        yield line.split("\t")

def main():
    worlds, items, order = [], {}, {}
    for r in rows(ROOT / "content" / "vocab.tsv"):
        if len(r) != 10:
            raise SystemExit(f"bad vocab row: {r}")
        world, id_, pic, en, pt, de, ru, q_en, q_pt, q_de = [c.strip() for c in r]
        if world not in order:
            order[world] = len(worlds)
            worlds.append({"id": world, "items": []})
        worlds[order[world]]["items"].append(id_)
        if re.fullmatch(r"#[0-9a-fA-F]{6}", pic):
            p = {"type": "color", "hex": pic.lower()}
        elif pic.isdigit():
            p = {"type": "count", "n": int(pic)}
        else:
            p = {"type": "emoji", "src": f"img/{id_}.svg"}
        if id_ in items:
            raise SystemExit(f"duplicate id {id_}")
        items[id_] = {"id": id_, "world": world, "pic": p,
                      "pt": {"word": pt, "q": q_pt}, "en": {"word": en, "q": q_en},
                      "de": {"word": de, "q": q_de}, "ru": ru}
    ui = {"ru": {}, "en": {}, "pt": {}, "de": {}}
    for r in rows(ROOT / "content" / "ui.tsv"):
        key, lang, text = r[0].strip(), r[1].strip(), "\t".join(r[2:]).strip()
        ui[lang][key] = text
    data = {
        "langs": ["pt", "en", "de"], "worlds": worlds, "items": items, "ui": ui,
        "audioPath": {"word": "audio/{lang}/{id}.ogg", "q": "audio/{lang}/{id}_q.ogg",
                      "gloss": "audio/ru/{id}.ogg", "ui": "audio/ui/{lang}_{key}.ogg"},
        "uiImg": {"star": "img/ui_star.svg", "chest": "img/ui_chest.svg", "home": "img/ui_home.svg",
                  "flag_pt": "img/flag_pt.svg", "flag_en": "img/flag_en.svg", "flag_de": "img/flag_de.svg",
                  "album": "img/ui_album.svg", "fox_run": "img/ui_run.svg"},
    }
    out = ROOT / "app" / "js" / "data.js"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("// GENERATED by tools/build_data.py from content/*.tsv - do not edit\n"
                   "window.GAME_DATA = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n",
                   encoding="utf-8")
    print(f"data.js: {len(items)} items, {len(worlds)} worlds, ui " +
          ", ".join(f"{k}={len(v)}" for k, v in ui.items()))

if __name__ == "__main__":
    main()
