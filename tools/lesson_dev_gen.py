#!/usr/bin/env python3
"""Builds tools/lesson_dev.html + tools/lesson_dev_ui.js: the real app page plus the lesson files, with the cs_* texts injected
(so lessons can be played before content/ui.tsv, build_data.py and app/index.html carry them). Dev/test harness only; never shipped.
Run: python3 tools/lesson_dev_gen.py   then open tools/lesson_dev.html (or run tools/smoke_lesson.js --dev)."""
import json, os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rows = {}
for ln in open(os.path.join(ROOT, 'content', 'lessons_ui.tsv'), encoding='utf-8'):
    if ln.startswith('#') or not ln.strip():
        continue
    k, lang, text = ln.rstrip('\n').split('\t', 2)
    if lang == 'ru':
        rows[k] = text
js = '/* generated by tools/lesson_dev_gen.py */\nwindow.GAME_DATA.ui.ru = Object.assign(window.GAME_DATA.ui.ru, %s);\n' % json.dumps(rows, ensure_ascii=False)
open(os.path.join(ROOT, 'tools', 'lesson_dev_ui.js'), 'w', encoding='utf-8').write(js)
html = open(os.path.join(ROOT, 'app', 'index.html'), encoding='utf-8').read()
html = html.replace('<head>', '<head>\n<base href="../app/">', 1)
if 'css/lesson.css' not in html:
    html = html.replace('</head>', '<link rel="stylesheet" href="css/lesson.css">\n</head>', 1)
if 'js/lesson.js' not in html:
    html = html.replace('<script src="js/main.js"></script>',
        '<script src="js/lessons_data.js"></script>\n<script src="js/lessons_art.js"></script>\n<script src="js/lesson.js"></script>\n<script src="js/main.js"></script>', 1)
html = html.replace('<script src="js/core.js"></script>', '<script src="js/core.js"></script>\n<script src="../tools/lesson_dev_ui.js"></script>', 1)
open(os.path.join(ROOT, 'tools', 'lesson_dev.html'), 'w', encoding='utf-8').write(html)
print('ok', len(rows), 'cs keys')
